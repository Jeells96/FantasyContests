import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' });
const p = await (await b.newContext({ viewport: { width: 390, height: 844 }, ignoreHTTPSErrors: true })).newPage();
await p.goto('http://localhost:4173/', { waitUntil: 'domcontentloaded' });
await p.evaluate(() => {
  localStorage.setItem('fantasycontests.device.v1', '8feaff05f25b4817ab306dd21d09765a');
  localStorage.setItem('fantasycontests.identity.v1', JSON.stringify({ firstName: 'Jaren', lastName: 'Eells', displayName: 'Jaren Eells', savedAt: new Date().toISOString() }));
});
await p.reload({ waitUntil: 'domcontentloaded' });
await p.waitForTimeout(3000);
await p.waitForSelector('.grid--contests .card', { timeout: 90000 });
const links = await p.evaluate(() => [...document.querySelectorAll('.grid--contests .card')].map((c) => ({ text: c.innerText.split('\n')[0], href: c.querySelector('a')?.getAttribute('href') })));
const nine = links.find((l) => l.text.includes('Wild Card'));
await p.goto(`http://localhost:4173${nine.href}`, { waitUntil: 'domcontentloaded' });
await p.waitForTimeout(25000);
await p.waitForTimeout(3000);
console.log('roster rows:', await p.evaluate(() => document.querySelectorAll('.slot').length));
console.log('spots label:', await p.evaluate(() => [...document.querySelectorAll('.section-title')].map((x) => x.innerText.replace(/\n/g, ' ')).join(' | ')));
console.log('footer:', await p.evaluate(() => document.querySelector('.footerbar, .sticky-footer, footer')?.innerText?.replace(/\n/g, ' | ') ?? 'n/a'));
console.log('howto:', await p.evaluate(() => document.querySelector('.howto')?.innerText.replace(/\n/g, ' | ') ?? 'n/a'));
await b.close();
